package Composicao;

public class Comodo {
    private String nome;
    private double areaM2;

    public Comodo(String nome, double areaM2) {
        this.nome = nome;
        this.areaM2 = areaM2;
    }

    public String getNome() {
        return nome;
    }

    public double getAreaM2() {
        return areaM2;
    }
}
